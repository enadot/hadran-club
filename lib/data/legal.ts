/**
 * The club's legal documents: the club rules, the privacy policy and the terms of
 * use for this site.
 *
 * They live here rather than in the pages because that is where every other piece of
 * site copy lives, and because these three are the texts most likely to come back
 * from a lawyer marked up. One file, three documents, one renderer.
 *
 * Written to describe the club as it actually works: membership comes with being a
 * Hadran customer and is not sold; the card is ordered in the שירות ותמיכה app and
 * never on this site; the site collects personal detail in exactly two places — the
 * activation form and the merchant enquiry — and the balance lookup stores nothing.
 * If any of that changes, these change with it.
 *
 * The wording has not been through legal review. `REVIEW_NOTE` says so on the page,
 * and is one line to delete once it has.
 */

